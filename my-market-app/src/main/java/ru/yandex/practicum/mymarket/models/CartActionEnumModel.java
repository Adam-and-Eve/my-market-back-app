package ru.yandex.practicum.mymarket.models;

/**
 * <summary>
 * Перечисление, определяющее доступные действия над товарными позициями в корзине покупателя.
 * Используется для маршрутизации бизнес-логики при изменении состава или количества товаров.
 * </summary>
 **/
public enum CartActionEnumModel {

    // region Values

    /**
     * Увеличение количества выбранного товара на единицу.
     **/
    PLUS,

    /**
     * Уменьшение количества выбранного товара на единицу.
     **/
    MINUS,

    /**
     * Полное удаление товарной позиции из корзины независимо от её текущего количества.
     **/
    DELETE

    // endregion
}